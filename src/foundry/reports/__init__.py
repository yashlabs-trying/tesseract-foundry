from ..models import ServiceRecommendation, DeploymentCandidate, EconomicEvaluation, PerformanceEvidence, RejectedReason
from typing import Optional

def generate_markdown_report(rec: ServiceRecommendation, candidates: Optional[dict[str, DeploymentCandidate]] = None) -> str:
    lines = []
    lines.append("# Tesseract Foundry - Deployment Recommendation Report")
    lines.append(f"\n**Recommendation ID:** {rec.recommendation_id}")
    lines.append(f"**Status:** {rec.approval_status}")
    lines.append(f"**Created:** {rec.created_at.isoformat() if rec.created_at else 'N/A'}")

    if rec.recommended_candidate_id == "NO_FEASIBLE_DEPLOYMENT":
        lines.append("\n## NO FEASIBLE DEPLOYMENT")
        lines.append("No candidate configuration satisfied all constraints.\n")
        if rec.rejected_candidates:
            lines.append("### Rejected Candidates")
            for r in rec.rejected_candidates:
                lines.append(f"- **{r.candidate_id}:** {r.reason}")
        return "\n".join(lines)

    lines.append(f"\n## Recommended Candidate: {rec.recommended_candidate_id}")
    cand = candidates.get(rec.recommended_candidate_id) if candidates else None
    if cand:
        lines.append(f"- Engine: {cand.serving_engine.value} v{cand.engine_version}")
        lines.append(f"- Precision: {cand.precision.value}")
        lines.append(f"- Tensor Parallelism: {cand.tensor_parallelism}")
        lines.append(f"- GPU Count: {cand.gpu_count}")
        lines.append(f"- Expected VRAM: {cand.expected_vram_gb:.1f} GB")
        lines.append(f"- Max Batch Size: {cand.max_batch_size}")
        lines.append(f"- Max Context: {cand.max_context_length}")

    if rec.economic_assumptions:
        econ = rec.economic_assumptions
        lines.append("\n## Economics")
        lines.append(f"- Monthly GPU Cost: ")
        lines.append(f"- Monthly Variable Cost: ")
        lines.append(f"- **Total Monthly Cost: **")
        lines.append(f"- Estimated Monthly Revenue: ")
        lines.append(f"- **Contribution Margin:  ({econ.margin_pct:.1f}%)**")
        if econ.break_even_requests_per_month:
            lines.append(f"- Break-Even Requests/Month: {econ.break_even_requests_per_month:,.0f}")
        lines.append(f"- Predicted Utilization: {econ.predicted_utilization_pct:.1f}%")
        lines.append(f"- Cost per Million Input Tokens: ")
        lines.append(f"- Cost per Million Output Tokens: ")

    if rec.expected_performance:
        perf = rec.expected_performance
        lines.append("\n## Expected Performance")
        lines.append(f"- Type: {perf.evidence_type.value}")
        if perf.ttft_ms:
            lines.append(f"- TTFT P50: {perf.ttft_ms.p50}ms / P95: {perf.ttft_ms.p95}ms")
        if perf.itl_ms:
            lines.append(f"- ITL P50: {perf.itl_ms.p50}ms / P95: {perf.itl_ms.p95}ms")
        if perf.request_latency_ms:
            lines.append(f"- Request Latency P50: {perf.request_latency_ms.p50}ms / P95: {perf.request_latency_ms.p95}ms")
        if perf.throughput:
            lines.append(f"- Throughput: {perf.throughput.completed_requests_per_second} rps")
        lines.append(f"- Sample Count: {perf.sample_count}")
        lines.append(f"- Error Rate: {perf.error_rate:.2%}")
        lines.append(f"- Confidence: {perf.evidence_type.value}")

    if rec.feasible_candidates:
        lines.append("\n## Feasible Alternatives")
        for cid in rec.feasible_candidates:
            if cid != rec.recommended_candidate_id:
                lines.append(f"- {cid}")

    if rec.rejected_candidates:
        lines.append("\n## Rejected Candidates")
        for r in rec.rejected_candidates:
            lines.append(f"- **{r.candidate_id}:** {r.reason}")

    if rec.deployment_artifact_ref:
        lines.append(f"\n## Deployment Artifact: {rec.deployment_artifact_ref}")

    lines.append("\n---\n*Report generated by Tesseract Foundry*")
    return "\n".join(lines)

def generate_json_report(rec: ServiceRecommendation) -> dict:
    return rec.model_dump()
